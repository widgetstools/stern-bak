#!/usr/bin/env node
/**
 * gen-consumer-tsconfig.mjs — emit `tsconfig.consumer.json` at the repo root.
 *
 * Why this exists
 * ---------------
 * Apps used to live at `apps/` *inside* this repo, so their `tsc --noEmit`
 * resolved `@wellsfargo-starui/*` through the repo-root
 * `node_modules/@wellsfargo-starui/<short>` workspace symlinks — reachable only
 * because the app sat below the repo root. Once the apps move to their own
 * repository that ancestor lookup is gone and every import fails TS2307.
 *
 * Vite is unaffected: `staruiViteAliases()` resolves to absolute paths derived
 * from THIS file's location, so it keeps working from anywhere. This script
 * gives `tsc` the same reach.
 *
 * TypeScript resolves `paths` relative to the config file that declares them,
 * so a config emitted here resolves into this repo no matter who extends it:
 *
 *     // consumer app tsconfig.json
 *     { "extends": "@wellsfargo-starui/platform/tsconfig.consumer.json" }
 *
 * Resolution preference mirrors `staruiViteAliases` exactly — built `dist/`
 * when present, live `src/` as the fallback — so `tsc` and the bundler never
 * disagree about which copy of a package they are looking at. Note that once
 * `build:packages` has run, that means dist for nearly everything; src only
 * wins for packages whose dist has not been emitted.
 *
 * Regenerated by `build:packages` so it cannot drift from the export maps.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { findMemberFolder, readManifest } from './staruiConsumerAliases.mjs';

const REPO_ROOT = resolve(import.meta.dirname, '..');
const OUT_PATH = join(REPO_ROOT, 'tsconfig.consumer.json');

// Angular is excluded from the build pipeline (see CLAUDE.md): its source is
// never built, and mapping it would point tsc at unbuilt Angular source. The
// angular-* buckets have been deleted, so host-data-angular is all that is left.
// Mirrors SKIP_MEMBERS in scripts/pack-npm.mjs.
const ANGULAR_MEMBERS = new Set(['@wellsfargo-starui/host-data-angular']);

/**
 * Pick an export target for TYPE resolution.
 *
 * Deliberately prefers the `types` condition, unlike the bundler path which
 * prefers `import` — tsc wants the `.d.ts`, Vite wants the `.js`.
 */
function typeTarget(value) {
  if (typeof value === 'string') return value;
  if (value && typeof value === 'object') {
    return value.types ?? value.import ?? value.default ?? null;
  }
  return null;
}

/** Candidate `src/` files for a `dist/` target, in preference order. */
function srcCandidates(rel) {
  const base = rel.replace(/^dist\//, 'src/');
  return [
    base.replace(/\.d\.ts$/, '.ts'),
    base.replace(/\.d\.ts$/, '.tsx'),
    base.replace(/\.js$/, '.ts'),
    base.replace(/\.js$/, '.tsx'),
    base,
  ];
}

/**
 * Absolute path for one export target — built output when it exists, live
 * source otherwise. Mirrors `resolveMemberPath` in staruiConsumerAliases.mjs.
 */
function resolveTarget(pkgDir, relTarget) {
  const rel = relTarget.replace(/^\.\//, '');
  const primary = join(pkgDir, rel);
  if (existsSync(primary)) return primary;

  for (const candidate of srcCandidates(rel)) {
    const abs = join(pkgDir, candidate);
    if (existsSync(abs)) return abs;
  }
  for (const entry of ['src/index.ts', 'src/index.tsx']) {
    const abs = join(pkgDir, entry);
    if (existsSync(abs)) return abs;
  }
  return primary;
}

function buildPaths() {
  const manifest = readManifest();
  if (!manifest) throw new Error('[gen-consumer-tsconfig] could not resolve the package manifest');

  const paths = {};
  let members = 0;

  for (const [bucketName, entry] of Object.entries(manifest)) {
    if (!entry?.members?.length || !entry.bucket) continue;

    for (const member of entry.members) {
      if (ANGULAR_MEMBERS.has(member)) continue;
      const folder = findMemberFolder(entry.bucket, member);
      const pkgDir = join(REPO_ROOT, 'packages', entry.bucket, folder);
      const pkgJsonPath = join(pkgDir, 'package.json');
      if (!existsSync(pkgJsonPath)) continue;
      members += 1;

      const pkg = JSON.parse(readFileSync(pkgJsonPath, 'utf8'));
      const short = member.split('/').pop();
      const exportsMap =
        pkg.exports && typeof pkg.exports === 'object'
          ? pkg.exports
          : { '.': pkg.types ?? pkg.main ?? './src/index.ts' };

      for (const [key, value] of Object.entries(exportsMap)) {
        const target = typeTarget(value);
        // Wildcard subpaths cannot be expressed as a single mapping; consumers
        // import concrete subpaths, which are all enumerated above.
        if (typeof target !== 'string' || target.includes('*') || key.includes('*')) continue;

        const abs = resolveTarget(pkgDir, target);
        const relPath = `./${relative(REPO_ROOT, abs).replace(/\\/g, '/')}`;
        const suffix = key === '.' ? '' : key.replace(/^\./, '');

        paths[`${member}${suffix}`] = [relPath];
        // Bucket-qualified form, matching the aliases staruiViteAliases emits.
        if (member !== bucketName) paths[`${bucketName}/${short}${suffix}`] = [relPath];
      }
    }
  }

  return { paths, members };
}

const { paths, members } = buildPaths();

const config = {
  extends: './tsconfig.base.json',
  compilerOptions: {
    paths: Object.fromEntries(Object.entries(paths).sort(([a], [b]) => a.localeCompare(b))),
  },
};

// tsconfig is JSONC, so the provenance banner can be a real comment.
const banner = [
  '// GENERATED by scripts/gen-consumer-tsconfig.mjs — do not edit by hand.',
  '// Regenerated by `npm run build:packages`.',
  '//',
  '// Lets a consumer app OUTSIDE this repo resolve @wellsfargo-starui/* with tsc:',
  '//   { "extends": "@wellsfargo-starui/platform/tsconfig.consumer.json" }',
  '',
].join('\n');

writeFileSync(OUT_PATH, `${banner}${JSON.stringify(config, null, 2)}\n`, 'utf8');

process.stdout.write(
  `[gen-consumer-tsconfig] wrote tsconfig.consumer.json — ${Object.keys(paths).length} path mappings across ${members} packages\n`,
);
